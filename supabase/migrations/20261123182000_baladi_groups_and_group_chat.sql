create table if not exists public.baladi_groups (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(btrim(name)) between 3 and 28),
  description text not null default '' check (char_length(description) <= 240),
  leader_id uuid not null references auth.users(id) on delete cascade,
  capacity integer not null default 20 check (capacity >= 20 and capacity % 5 = 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index if not exists baladi_groups_name_lower_uidx on public.baladi_groups(lower(name));

create table if not exists public.baladi_group_members (
  group_id uuid not null references public.baladi_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member','veteran','deputy','leader')),
  joined_at timestamptz not null default now(),
  primary key (group_id,user_id),
  unique (user_id)
);
create index if not exists baladi_group_members_group_role_idx on public.baladi_group_members(group_id,role);

create table if not exists public.baladi_group_messages (
  id bigint generated by default as identity primary key,
  group_id uuid not null,
  user_id uuid not null,
  body text,
  sticker_id text references public.baladi_cosmetic_catalog(id),
  is_pinned boolean not null default false,
  pinned_by uuid references auth.users(id),
  pinned_at timestamptz,
  created_at timestamptz not null default now(),
  constraint baladi_group_message_member_fk foreign key(group_id,user_id)
    references public.baladi_group_members(group_id,user_id) on delete cascade,
  constraint baladi_group_message_content_check check (
    (body is not null and sticker_id is null and char_length(btrim(body)) between 1 and 350)
    or (body is null and sticker_id is not null)
  )
);
create index if not exists baladi_group_messages_group_created_idx
  on public.baladi_group_messages(group_id,created_at desc);

alter table public.baladi_groups enable row level security;
alter table public.baladi_group_members enable row level security;
alter table public.baladi_group_messages enable row level security;

create or replace function public.baladi_create_group(p_user_id uuid,p_name text,p_description text default '')
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_name text := btrim(coalesce(p_name,''));
  v_group public.baladi_groups%rowtype;
begin
  if char_length(v_name) < 3 or char_length(v_name) > 28 then raise exception 'نام گروه باید بین ۳ تا ۲۸ نویسه باشد.'; end if;
  if v_name ~ '[[:cntrl:]]' then raise exception 'نام گروه معتبر نیست.'; end if;
  if exists(select 1 from public.baladi_group_members where user_id=p_user_id) then
    raise exception 'هر بازیکن فقط می‌تواند عضو یک گروه باشد.';
  end if;
  insert into public.baladi_groups(name,description,leader_id)
  values(v_name,left(btrim(coalesce(p_description,'')),240),p_user_id)
  returning * into v_group;
  insert into public.baladi_group_members(group_id,user_id,role)
  values(v_group.id,p_user_id,'leader');
  return jsonb_build_object('group',to_jsonb(v_group),'role','leader','member_count',1);
end;
$$;

create or replace function public.baladi_join_group(p_user_id uuid,p_group_id uuid)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_group public.baladi_groups%rowtype;
  v_count integer;
begin
  if exists(select 1 from public.baladi_group_members where user_id=p_user_id) then
    raise exception 'هر بازیکن فقط می‌تواند عضو یک گروه باشد.';
  end if;
  select * into v_group from public.baladi_groups where id=p_group_id for update;
  if not found then raise exception 'گروه پیدا نشد.'; end if;
  select count(*) into v_count from public.baladi_group_members where group_id=p_group_id;
  if v_count >= v_group.capacity then raise exception 'ظرفیت این گروه تکمیل شده است.'; end if;
  insert into public.baladi_group_members(group_id,user_id,role)
  values(p_group_id,p_user_id,'member');
  return jsonb_build_object('group',to_jsonb(v_group),'role','member','member_count',v_count+1);
end;
$$;

create or replace function public.baladi_upgrade_group_capacity(p_user_id uuid,p_group_id uuid,p_new_capacity integer)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_group public.baladi_groups%rowtype;
  v_profile public.baladi_game_profiles%rowtype;
  v_blocks integer;
  v_cost integer;
begin
  select * into v_group from public.baladi_groups where id=p_group_id for update;
  if not found then raise exception 'گروه پیدا نشد.'; end if;
  if v_group.leader_id <> p_user_id then raise exception 'فقط رهبر گروه می‌تواند ظرفیت را افزایش دهد.'; end if;
  if p_new_capacity <= v_group.capacity or p_new_capacity % 5 <> 0 then
    raise exception 'ظرفیت جدید باید حداقل ۵ نفر بیشتر و مضربی از ۵ باشد.';
  end if;
  v_blocks := (p_new_capacity-v_group.capacity)/5;
  v_cost := v_blocks*50000;
  select * into v_profile from public.baladi_game_profiles where user_id=p_user_id for update;
  if not found or v_profile.coins < v_cost then raise exception 'برای افزایش ظرفیت به %s سکه نیاز داری.',v_cost; end if;
  update public.baladi_game_profiles set coins=coins-v_cost,updated_at=now() where user_id=p_user_id returning * into v_profile;
  update public.baladi_groups set capacity=p_new_capacity,updated_at=now() where id=p_group_id returning * into v_group;
  return jsonb_build_object('group',to_jsonb(v_group),'profile',to_jsonb(v_profile),'cost',v_cost);
end;
$$;

create or replace function public.baladi_set_group_role(p_actor_id uuid,p_group_id uuid,p_target_id uuid,p_role text)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_actor text;
  v_target text;
begin
  if p_role not in ('member','veteran','deputy') then raise exception 'مقام انتخاب‌شده معتبر نیست.'; end if;
  select role into v_actor from public.baladi_group_members where group_id=p_group_id and user_id=p_actor_id;
  select role into v_target from public.baladi_group_members where group_id=p_group_id and user_id=p_target_id;
  if v_actor is null or v_target is null then raise exception 'عضو گروه پیدا نشد.'; end if;
  if p_actor_id=p_target_id then raise exception 'نمی‌توانی مقام خودت را تغییر دهی.'; end if;
  if v_actor='leader' then
    update public.baladi_group_members set role=p_role where group_id=p_group_id and user_id=p_target_id;
  elsif v_actor='deputy' and v_target in ('member','veteran') and p_role in ('member','veteran') then
    update public.baladi_group_members set role=p_role where group_id=p_group_id and user_id=p_target_id;
  else
    raise exception 'اجازه تغییر مقام این عضو را نداری.';
  end if;
  return jsonb_build_object('ok',true,'user_id',p_target_id,'role',p_role);
end;
$$;

create or replace function public.baladi_remove_group_member(p_actor_id uuid,p_group_id uuid,p_target_id uuid)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_actor text;
  v_target text;
begin
  select role into v_actor from public.baladi_group_members where group_id=p_group_id and user_id=p_actor_id;
  select role into v_target from public.baladi_group_members where group_id=p_group_id and user_id=p_target_id;
  if v_actor is null or v_target is null then raise exception 'عضو گروه پیدا نشد.'; end if;
  if p_actor_id=p_target_id or v_target='leader' then raise exception 'رهبر باید ابتدا رهبری را منتقل کند.'; end if;
  if not (v_actor='leader' or (v_actor='deputy' and v_target in ('member','veteran'))) then
    raise exception 'اجازه حذف این عضو را نداری.';
  end if;
  delete from public.baladi_group_members where group_id=p_group_id and user_id=p_target_id;
  return jsonb_build_object('ok',true,'removed_user_id',p_target_id);
end;
$$;

create or replace function public.baladi_transfer_group_leadership(p_user_id uuid,p_group_id uuid,p_target_id uuid)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
begin
  if not exists(select 1 from public.baladi_groups where id=p_group_id and leader_id=p_user_id for update) then
    raise exception 'فقط رهبر فعلی می‌تواند رهبری را منتقل کند.';
  end if;
  if not exists(select 1 from public.baladi_group_members where group_id=p_group_id and user_id=p_target_id) then
    raise exception 'بازیکن انتخاب‌شده عضو این گروه نیست.';
  end if;
  update public.baladi_group_members set role='deputy' where group_id=p_group_id and user_id=p_user_id;
  update public.baladi_group_members set role='leader' where group_id=p_group_id and user_id=p_target_id;
  update public.baladi_groups set leader_id=p_target_id,updated_at=now() where id=p_group_id;
  return jsonb_build_object('ok',true,'new_leader_id',p_target_id);
end;
$$;

create or replace function public.baladi_leave_group(p_user_id uuid,p_group_id uuid)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_role text;
begin
  select role into v_role from public.baladi_group_members where group_id=p_group_id and user_id=p_user_id;
  if v_role is null then raise exception 'عضو این گروه نیستی.'; end if;
  if v_role='leader' then raise exception 'رهبر باید ابتدا رهبری را منتقل کند.'; end if;
  delete from public.baladi_group_members where group_id=p_group_id and user_id=p_user_id;
  return jsonb_build_object('ok',true);
end;
$$;

create or replace function public.baladi_send_group_message(p_user_id uuid,p_group_id uuid,p_body text default null,p_sticker_id text default null)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_body text := nullif(btrim(coalesce(p_body,'')),'');
  v_message public.baladi_group_messages%rowtype;
begin
  if not exists(select 1 from public.baladi_group_members where group_id=p_group_id and user_id=p_user_id) then
    raise exception 'برای ارسال پیام باید عضو گروه باشی.';
  end if;
  if p_sticker_id is null then
    if v_body is null or char_length(v_body)>350 then raise exception 'پیام باید بین ۱ تا ۳۵۰ نویسه باشد.'; end if;
  else
    if v_body is not null then raise exception 'ارسال متن و استیکر هم‌زمان مجاز نیست.'; end if;
    if not exists(select 1 from public.baladi_user_cosmetics where user_id=p_user_id and cosmetic_id=p_sticker_id) then
      raise exception 'ابتدا باید این استیکر را بخری.';
    end if;
  end if;
  insert into public.baladi_group_messages(group_id,user_id,body,sticker_id)
  values(p_group_id,p_user_id,v_body,p_sticker_id)
  returning * into v_message;
  return jsonb_build_object('id',v_message.id,'group_id',v_message.group_id,'user_id',v_message.user_id,'body',v_message.body,'sticker_id',v_message.sticker_id,'created_at',v_message.created_at);
end;
$$;

create or replace function public.baladi_pin_group_message(p_user_id uuid,p_group_id uuid,p_message_id bigint,p_pinned boolean)
returns jsonb
language plpgsql
set search_path=public,pg_temp
as $$
declare
  v_role text;
begin
  select role into v_role from public.baladi_group_members where group_id=p_group_id and user_id=p_user_id;
  if v_role not in ('veteran','deputy','leader') then raise exception 'فقط پیشکسوت، قائم‌مقام یا رهبر می‌تواند پیام را سنجاق کند.'; end if;
  update public.baladi_group_messages
  set is_pinned=p_pinned,pinned_by=case when p_pinned then p_user_id else null end,pinned_at=case when p_pinned then now() else null end
  where id=p_message_id and group_id=p_group_id;
  if not found then raise exception 'پیام گروه پیدا نشد.'; end if;
  return jsonb_build_object('ok',true);
end;
$$;

